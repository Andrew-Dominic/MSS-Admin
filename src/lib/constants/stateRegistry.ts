/**
 * Returns configuration metadata for a given state
 */
export function getStateConfig(state: string): StateMetadata {
  return (
    STATE_REGISTRY[state] || {
      state,
      codePrefix: state.substring(0, 2).toUpperCase(),
      languageCode: "hi",
      languageName: "Hindi & Regional",
      languageNative: "हिन्दी / Regional",
      ministry: `Department of Industries, Government of ${state}`,
      authority: `Directorate of Industries, ${state}`,
      implementingAgency: `District Industries Centres (DIC ${state})`,
      sampleTitle: `[${state}] ${state} MSME Promotion & Industrial Assistance Scheme`,
      portalUrl: `https://${state.toLowerCase().replace(/[^a-z0-9]/g, "")}.gov.in`,
    }
  );
}

/**
 * Generates an official state-prefixed scheme code adhering to MSME conventions
 * Example: "Maharashtra" -> "MH-MSME2526-104"
 */
export function generateStateSchemeCode(state: string, existingCode?: string): string {
  const meta = getStateConfig(state);
  const now = new Date();
  const yr = now.getFullYear();
  // Financial year (e.g. 2526 for 2025-2026, or 2627 for 2026-2027)
  const currentMonth = now.getMonth(); // 0-indexed (April is 3)
  const fyStart = currentMonth >= 3 ? yr : yr - 1;
  const fyString = `${fyStart.toString().slice(-2)}${(fyStart + 1).toString().slice(-2)}`;
  
  // 3-digit random sequence
  const randomSeq = Math.floor(100 + Math.random() * 900);

  if (state === "All India") {
    return `MSME${fyString}-${randomSeq}`;
  }

  return `${meta.codePrefix}-MSME${fyString}-${randomSeq}`;
}

/**
 * Returns primary language metadata for a state
 */
export function getStateLanguage(state: string): {
  code: string;
  name: string;
  native: string;
} {
  const config = getStateConfig(state);
  return {
    code: config.languageCode,
    name: config.languageName,
    native: config.languageNative,
  };
}
